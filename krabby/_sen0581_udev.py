"""SEN0581 per-robot serial→role map and udev rule generation.

HAL catalog rows always open portable paths ``/dev/krabby-tof-*``. Each Orin keeps
its own USB serial assignment in ``/etc/krabby/sen0581.json``; ``krabby install``
renders ``/etc/udev/rules.d/99-krabby-sen0581.rules`` from that file.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Mapping

SEN0581_CONFIG_PATH = Path("/etc/krabby/sen0581.json")
SEN0581_UDEV_PATH = Path("/etc/udev/rules.d/99-krabby-sen0581.rules")

SEN0581_ROLES: tuple[str, ...] = ("belly_right", "belly_left", "rear")


def sen0581_symlink_name(role: str) -> str:
    """Udev ``SYMLINK`` basename for a mount role (e.g. ``belly_right`` → ``krabby-tof-belly-right``)."""
    if role not in SEN0581_ROLES:
        raise ValueError(f"unknown SEN0581 role {role!r}; expected one of {SEN0581_ROLES}")
    return f"krabby-tof-{role.replace('_', '-')}"


def sen0581_device_path(role: str) -> str:
    """Portable HAL / Docker path for a mount role (``/dev/krabby-tof-…``)."""
    return f"/dev/{sen0581_symlink_name(role)}"


def sen0581_device_paths() -> tuple[str, ...]:
    """All portable SEN0581 device paths in ``SEN0581_ROLES`` order."""
    return tuple(sen0581_device_path(role) for role in SEN0581_ROLES)


# Kept for call sites / tests that want role → basename without the ``/dev/`` prefix.
SEN0581_SYMLINK_BY_ROLE: dict[str, str] = {
    role: sen0581_symlink_name(role) for role in SEN0581_ROLES
}

_FTDI_VID = 0x0403
_FTDI_PID = 0x6010


def normalize_sen0581_serial(value: str) -> str:
    """Normalize to USB ``ATTRS{serial}`` form (space before the hex suffix).

    Accepts values like ``YYYYMM HEXID`` or ``YYYYMM_HEXID`` / ``ID_SERIAL_SHORT``.
    """
    raw = str(value).strip()
    if not raw:
        raise ValueError("SEN0581 serial must be non-empty")
    # ID_SERIAL_SHORT uses underscore; ATTRS{serial} uses a space.
    if "_" in raw and " " not in raw:
        raw = raw.replace("_", " ", 1)
    if not re.fullmatch(r"[0-9A-Za-z]+ [0-9A-Za-z]+", raw):
        raise ValueError(
            f"SEN0581 serial {value!r} must look like 'YYYYMM HEXID' "
            f"(or 'YYYYMM_HEXID' as in ID_SERIAL_SHORT)"
        )
    return raw


def load_sen0581_role_map(path: Path | None = None) -> dict[str, str]:
    """Load and validate ``{belly_right, belly_left, rear} → serial``."""
    cfg_path = path or SEN0581_CONFIG_PATH
    data = json.loads(cfg_path.read_text())
    if not isinstance(data, dict):
        raise ValueError(f"{cfg_path}: expected a JSON object")
    out: dict[str, str] = {}
    missing = [r for r in SEN0581_ROLES if r not in data]
    if missing:
        raise ValueError(f"{cfg_path}: missing roles {missing}")
    seen: set[str] = set()
    for role in SEN0581_ROLES:
        serial = normalize_sen0581_serial(str(data[role]))
        if serial in seen:
            raise ValueError(f"{cfg_path}: duplicate serial {serial!r}")
        seen.add(serial)
        out[role] = serial
    return out


def render_sen0581_udev_rules(role_to_serial: Mapping[str, str]) -> str:
    """Render udev rules that map each serial (if00) to ``/dev/krabby-tof-*``."""
    lines = [
        "# Generated by krabby install from /etc/krabby/sen0581.json — do not edit.",
        "# SEN0581 / Sipeed Meta Sense Lite (FT2232 Dual UART, 0403:6010).",
        "# Use interface 00 only (if01 is unused).",
        "",
    ]
    for role in SEN0581_ROLES:
        serial = normalize_sen0581_serial(role_to_serial[role])
        symlink = sen0581_symlink_name(role)
        lines.append(
            'SUBSYSTEM=="tty", ATTRS{idVendor}=="0403", ATTRS{idProduct}=="6010", '
            f'ATTRS{{serial}}=="{serial}", ENV{{ID_USB_INTERFACE_NUM}}=="00", '
            f'SYMLINK+="{symlink}", MODE="0666", GROUP="dialout"'
        )
    lines.append("")
    return "\n".join(lines)


def detect_sen0581_serials() -> list[str]:
    """Return unique USB serials for plugged SEN0581 if00 ports (ATTRS form)."""
    found: list[str] = []
    seen: set[str] = set()
    try:
        from serial.tools import list_ports
    except ImportError:
        return found
    for port in list_ports.comports():
        if port.vid != _FTDI_VID or port.pid != _FTDI_PID:
            continue
        # Prefer interface 00; LOCATION ends with ":1.0" on Linux.
        loc = port.location or ""
        if loc and not loc.endswith(":1.0"):
            continue
        sn = (port.serial_number or "").strip()
        if not sn:
            continue
        try:
            norm = normalize_sen0581_serial(sn)
        except ValueError:
            continue
        if norm in seen:
            continue
        seen.add(norm)
        found.append(norm)
    return sorted(found)


def draft_role_map_from_serials(serials: list[str]) -> dict[str, str]:
    """Deterministic first-boot assignment: sorted serials → belly_right, belly_left, rear."""
    if len(serials) != len(SEN0581_ROLES):
        raise ValueError(
            f"need exactly {len(SEN0581_ROLES)} SEN0581 serials, got {len(serials)}"
        )
    ordered = sorted(normalize_sen0581_serial(s) for s in serials)
    return {role: ordered[i] for i, role in enumerate(SEN0581_ROLES)}
