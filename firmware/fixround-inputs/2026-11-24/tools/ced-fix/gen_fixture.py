"""Writes tests/native/firmware/arduino/src/actuator/robot_end_current_replay.hpp.

Groups:
  endcur: the 40 design goldens (ced-design/goldens.json: endcur-111808 / -112315 jogs,
          samples up to the design reference's decision), re-judged by this reference.
  today:  every jog move of the 2026-11-24 PWM 128/150 logs (clearance-*, fr-recover,
          hipend, rodscale-*), first nonzero PWM to the host's stop.
  short:  real curl-end approaches started later (the drive begins `cut` full-PWM samples
          into the approach, ramp kept), each from the middle of the band the design
          reference called stuck, and one shortened FRHL mid-stroke stall.
Usage: python gen_fixture.py OUT.hpp
"""
import json
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import detector as det  # noqa: E402
import evaluate as ev  # noqa: E402

KINDS = {'static': 'Still', 'switch': 'Switch', 'mech': 'Stop', 'stuck': 'Stuck', 'none': 'None'}
SHORT = [  # (source move, cut): mid-band of the design reference's stuck verdicts
    ('endcur-111808#5', 12), ('endcur-111808#7', 6), ('endcur-111808#9', 9), ('endcur-111808#11', 152),
    ('endcur-111808#17', 20), ('endcur-112315#11', 146), ('endcur-112315#13', 142),
    ('clearance-FL-121754#6', 21), ('clearance-FR-115750#8', 15), ('hipend-FL-115546#2', 14),
    ('rodscale-knee_back_hip_out-114339#0', 136),
]
F1 = ('clearance-FR-115750#7', 5)


def verdict(samples, retract, curl):
    d = det.EndDetector(1, retract, curl, det.Params())
    for k, (e, i, r) in enumerate(samples):
        x = d.step(e, i, r)
        if x:
            return dict(kind=x.kind, k=k, edges=e)
    return dict(kind='none')


def main():
    out_path = sys.argv[1]
    moves = ev.load_all()
    by = {m[0]: m for m in moves}
    rows = []
    for m in moves:
        name, joint, pwm, s, retract, curl, exp, cat = m
        if cat == 'endcur':
            continue
        group = 'endcur' if cat == 'golden' else 'today'
        label = name if group == 'endcur' else name
        rows.append(dict(name=label, group=group, joint=joint, pwm=pwm, retract=retract, curl=curl,
                         samples=s, v=verdict(s, retract, curl)))
    for src, cut in SHORT + [F1]:
        m = by[src]
        v = ev.cut_variant(m[3], cut)
        # cut_variant pads 3 s of held count; keep only the real trace
        v = v[:len(v) - 60]
        rows.append(dict(name=f"{src} from +{cut}", group='short', joint=m[1], pwm=m[2], retract=m[4], curl=m[5],
                         samples=v, v=verdict(v, m[4], m[5])))
    w = []
    a = w.append
    a('#pragma once')
    a('')
    a('#include <stddef.h>')
    a('#include <stdint.h>')
    a('')
    a('#include "src/actuator/calibration_end_detector.h"')
    a('')
    a('// Robot end-current replays for test_calibration_end_detector.cpp. Data only,')
    a('// generated by the review-fix reference (ced-fix/gen_fixture.py and detector.py,')
    a('// the design stage\'s detector.py plus the 2026-11-24 review fixes) from front-leg')
    a('// jogs on a stand logged 2026-11-24. One sample per telemetry frame (about')
    a('// 51.5 ms) from the first nonzero PWM to the host\'s stop. Per sample: e = drive')
    a('// edges since the drive started, i = the frame\'s current field x 10 (tenths of an')
    a('// IS count; the telemetry truncates to whole counts), r = 1 once the PWM reached')
    a('// the move PWM. Groups:')
    a('//   endcur: the scripted end-current jogs at PWM 80/120/150 (firmware')
    a('//           hallcal-1123; endcur-111808 = FL leg, endcur-112315 = FR leg), each up')
    a('//           to the design reference\'s decision (the design goldens).')
    a('//   today:  every jog of the PWM 128/150 runs that followed (clearance-FL/FR,')
    a('//           fr-recover, hipend-FL, rodscale-*), among them the FRHL curl at 128')
    a('//           that stalled 878 edges short of its switch (clearance-FR-115750#7).')
    a('//   short:  real curl-end approaches started later in the same approach (the')
    a('//           drive begins that many full-PWM samples in, its ramp kept), each from')
    a('//           the middle of the band the design reference called stuck, and the')
    a('//           FRHL stall started 5 samples later.')
    a('// The expected verdict and its sample k are the reference\'s; kind None: the')
    a('// host stopped the move first.')
    a('')
    a('struct RobotEndSample')
    a('{')
    a('    int16_t e;')
    a('    uint16_t i;')
    a('    uint8_t r;')
    a('};')
    a('')
    a('enum class RobotEndGroup : uint8_t')
    a('{')
    a('    EndCurrent,  // endcur: the scripted end-current jogs')
    a('    Today,       // the PWM 128/150 runs')
    a('    Short,       // real end approaches started later')
    a('};')
    a('')
    a('struct RobotEndMove')
    a('{')
    a('    const char *name;   // log#move index')
    a('    RobotEndGroup group;')
    a('    const char *joint;')
    a('    int pwm;')
    a('    bool retract;       // -PWM: the rod retracts')
    a('    bool curl;')
    a('    CalibrationEnd expected;')
    a('    int k;              // sample index of the expected decision (-1: none)')
    a('    int edges;          // drive edges at the decision')
    a('    const RobotEndSample *samples;')
    a('    size_t count;')
    a('};')
    a('')
    groups = {'endcur': 'RobotEndGroup::EndCurrent', 'today': 'RobotEndGroup::Today', 'short': 'RobotEndGroup::Short'}
    for n, m in enumerate(rows):
        a('// %s %s PWM %d %s %s (expected %s)' % (m['name'], m['joint'], m['pwm'],
                                                'retract' if m['retract'] else 'extend',
                                                'curl' if m['curl'] else 'uncurl', m['v']['kind']))
        a('static const RobotEndSample kRobotEnd%d[] = {' % n)
        items = ['{%d, %d, %d}' % (e, i, r) for e, i, r in m['samples']]
        line = '   '
        for it in items:
            if len(line) + len(it) + 2 > 110:
                a(line.rstrip())
                line = '   '
            line += ' ' + it + ','
        a(line.rstrip())
        a('};')
    a('')
    a('static const RobotEndMove kRobotEndMoves[] = {')
    for n, m in enumerate(rows):
        v = m['v']
        a('    {"%s", %s, "%s", %d, %s, %s, CalibrationEnd::%s, %d, %d, kRobotEnd%d,' % (
            m['name'], groups[m['group']], m['joint'], m['pwm'], 'true' if m['retract'] else 'false',
            'true' if m['curl'] else 'false', KINDS[v['kind']], v.get('k', -1), v.get('edges', 0), n))
        a('     sizeof(kRobotEnd%d) / sizeof(kRobotEnd%d[0])},' % (n, n))
    a('};')
    a('static constexpr size_t kRobotEndMoveCount = sizeof(kRobotEndMoves) / sizeof(kRobotEndMoves[0]);')
    a('')
    open(out_path, 'w', newline='\n').write('\n'.join(w))
    print(len(rows), 'moves', sum(len(m['samples']) for m in rows), 'samples')
    for g in ('endcur', 'today', 'short'):
        c = Counter(m['v']['kind'] for m in rows if m['group'] == g)
        print(g, sum(c.values()), dict(c))
    for m in rows:
        if m['group'] == 'short' or m['name'] == 'clearance-FR-115750#7':
            print(m['name'], m['joint'], m['pwm'], m['v'], len(m['samples']))


if __name__ == '__main__':
    main()
