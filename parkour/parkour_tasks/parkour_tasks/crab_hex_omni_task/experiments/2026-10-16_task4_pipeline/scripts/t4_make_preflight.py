#!/usr/bin/env python3
"""Write ``preflight/candidates.yaml`` -- the Phase-A stage smokes (PLAN step 2, DESIGN §5 row A) as run_candidates
REFERENCE chains.

Every stage is the SHIPPED lineage stage verbatim (ppo_construction FB6k__B / SF__B_c4_s18 / SF__B_rest_s18 stages,
phase-2 P2__S1_s18 p2a): same base, overlay, categories and chain-level keys. Only three things change:
- iterations: 20;
- no stage eval;
- the resume: s1 trains from scratch, and c4 / c5 / c6 / c6x / p2a resume the BUNDLED lineage head of the previous
  stage (``OMNI/policy/<n>_*/model_*.pt``) by explicit checkpoint path.

The smokes feed P-config (the trainer-written params against the lineage run dirs) and P-early (s1's first 20 its
against X43, bitwise per tfevents tag). Seed 18 throughout.

    t4_make_preflight.py
"""

from __future__ import annotations

import copy
import hashlib
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
C = HERE.parent
EXP = C.parent
R = Path(__file__).resolve().parents[7]  # this checkout's root (scripts -> campaign -> experiments -> ... -> repo)
POLICY = EXP.parent / "policy"
ITERS = 20
SEED = 18
# stage -> (shipped chain, bundled head the stage resumes; None = from scratch)
RESUME = {
    "s1": None,
    "c4": "1_fb6k/model_5999.pt",
    "c5": "2_c4/model_7498.pt",
    "c6": "3_c5/model_8997.pt",
    "c6x": "4_c6/model_10996.pt",
    "p2a": "5_c6x_clockfree/model_14995.pt",
}


def shipped() -> dict:
    """stage name -> (chain-level keys, stage dict), straight from the shipped candidates files."""
    pc = yaml.safe_load((EXP / "2026-10-01_ppo_construction/candidates.yaml").read_text())["chains"]
    p2 = yaml.safe_load((EXP / "2026-10-07_omni_phase2/candidates.yaml").read_text())["chains"]
    out = {}
    for cname in ("FB6k__B", "SF__B_c4_s18", "SF__B_rest_s18"):
        ch = pc[cname]
        top = {k: v for k, v in ch.items() if k not in ("stages", "notes")}
        for s in ch["stages"]:
            out[s["stage"]] = (top, s)
    ch = p2["P2__S1_s18"]
    out["p2a"] = ({k: v for k, v in ch.items() if k not in ("stages", "notes")}, ch["stages"][0])
    return out


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    st = shipped()
    chains, refs = {}, {}
    for name, head in RESUME.items():
        top, s = st[name]
        stg = copy.deepcopy(s)
        stg["iters"] = ITERS
        stg["eval"] = []
        if head is None:
            stg["from_scratch"] = True
            stg["resume_from"] = "scratch"
            note = "from scratch"
        else:
            p = POLICY / head
            stg["from_scratch"] = False
            stg["resume_from"] = {"checkpoint": str(p.relative_to(R))}
            note = f"resumes the bundled {head} (sha256 {sha256(p)[:16]})"
        cid = f"PF_{name}_s{SEED}"
        chains[cid] = {"notes": f"Task 4 Phase-A smoke (PLAN step 2): the shipped {name} stage, {ITERS} its, {note}.",
                       **copy.deepcopy(top), "stages": [stg]}
        refs[cid] = {"chain": cid, "seed": SEED}
    doc = {
        "schema": 1,
        "plant": "A15+B",
        "seeds": {"screen": SEED, "confirm": 16},
        "screen": {"chain": "PF_s1_s18", "eval": [], "iters": ITERS},
        "promotion": {"enabled": False},
        "baseline": {"id": "PF_s1_s18", "chain": "PF_s1_s18"},
        # phase 2's decision rule verbatim (the driver validates a complete rule_version-2 block); RECORD ONLY here.
        "decision_rule": {**copy.deepcopy(yaml.safe_load((EXP / "2026-10-07_omni_phase2/candidates.yaml").read_text())
                                          ["decision_rule"]),
                          "text": "TASK 4 PREFLIGHT (2026-10-16_task4_pipeline): RECORD ONLY. Phase-A smokes; the "
                                  "parity reads are scripts/t4_pconfig.py and scripts/t4_pearly.py."},
        "chains": chains,
        "references": refs,
        "candidates": [],
        "milestones": [],
    }
    out = C / "preflight" / "candidates.yaml"
    out.parent.mkdir(exist_ok=True)
    out.write_text("# GENERATED by scripts/t4_make_preflight.py -- do not edit by hand.\n"
                   + yaml.safe_dump(doc, sort_keys=False, width=120))
    print(f"{out}: {len(chains)} chains")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
