#!/usr/bin/env python3
"""Fault-injection sweep: write envs/<cell>__<row>[_L090].env from cells.yaml (CHARTER §4). Pure (no Isaac, no torch).

Each file = the row's base env (cells.yaml ``rows.<row>.base_env``: the rod-speed DR ``T00_nominal_L000_A__{suite,
field_light}.env``, the RT ``rt_kind_eval.env`` for the kind rows), its ``^KRABBY_`` lines only and in their order,
plus the cell's lines: ``KRABBY_FAULT=<id>:<level>`` + ``KRABBY_FAULT_ONSET=<row window>`` (+
``KRABBY_FAULT_FROM_START=1`` for S12 / D1), or an anchor's own ``env`` block (T10b: ``KRABBY_STRESS_VXY_ZERO=1``).
Nominals (``NOM``) and T12 (a checkpoint change) are the base lines alone. An ``_L090`` file is byte-identical to its
L000 twin: the payload comes from gate_row's ``TP_LEVEL_FILE`` (cells.yaml ``levels.L090``), never from the env
file. Which (cell, row, payload) files exist follows cells.yaml: suite + field_light for every cell, ledge_down +
pits for ``kind_rows`` cells (and the L000 nominal), ``_L090`` for ``payload: L090`` cells and the L090 nominal.

Every armed file is parsed back through ``fault_knobs.parse_fault_knobs`` (the launch-time parser), so a file that
would be refused at launch is refused here. ``--check`` writes nothing and exits 1 when envs/ differs from what
cells.yaml implies (a missing, stale or extra .env file).

    python3 scripts/make_envs.py [--check]
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
CAMPAIGN = HERE.parent
OMNI = CAMPAIGN.parents[1]                                   # crab_hex_omni_task
CELLS_YAML = CAMPAIGN / "cells.yaml"
ENVS = CAMPAIGN / "envs"
FAULT_KNOBS_PY = OMNI / "config" / "crab_hex" / "fault_knobs.py"
KIND_ROWS = ("ledge_down", "pits")
BASE_ROWS = ("suite", "field_light")
HEADER = ("# GENERATED by experiments/2026-11-15_fault_injection/scripts/make_envs.py from cells.yaml ({what}) -- do "
          "not edit by hand; regenerate. Launchers read ^KRABBY_ only.\n")


def _fault_knobs():
    spec = importlib.util.spec_from_file_location("fault_knobs__make_envs", FAULT_KNOBS_PY)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def load_cells(path: Path = CELLS_YAML) -> dict:
    doc = yaml.safe_load(path.read_text())
    if doc.get("schema") != "fault_cells/v1":
        raise SystemExit(f"{path}: schema {doc.get('schema')!r} != fault_cells/v1")
    return doc


def base_lines(doc: dict, row: str) -> list[str]:
    src = OMNI / doc["rows"][row]["base_env"]
    lines = [ln.rstrip("\n") for ln in src.read_text().splitlines() if ln.startswith("KRABBY_")]
    bad = [ln for ln in lines if ln.startswith(("KRABBY_FAULT", "KRABBY_STRESS_", "KRABBY_PAYLOAD_"))]
    if bad:
        raise SystemExit(f"{src}: a base env already sets {bad}")
    keys = [ln.split("=", 1)[0] for ln in lines]
    if len(keys) != len(set(keys)):
        raise SystemExit(f"{src}: duplicate keys")
    return lines


def cell_lines(cell: dict, row_spec: dict, onset: str | None = None) -> list[str]:
    out = []
    if cell.get("fault"):
        out.append(f"KRABBY_FAULT={cell['fault']}")
        out.append(f"KRABBY_FAULT_ONSET={onset or row_spec['onset']}")
        if cell.get("from_start"):
            out.append("KRABBY_FAULT_FROM_START=1")
    for k, v in (cell.get("env") or {}).items():
        if not str(k).startswith("KRABBY_"):
            raise SystemExit(f"cell {cell['id']}: env key {k!r} is not KRABBY_*")
        out.append(f"{k}={v}")
    return out


def planned(doc: dict) -> dict[str, str]:
    """``{file name: text}`` for every env file cells.yaml implies."""
    fk = _fault_knobs()
    files: dict[str, str] = {}

    def add(cid: str, row: str, payload: str, extra: list[str], what: str):
        name = f"{cid}__{row}{'' if payload == 'L000' else '_' + payload}.env"
        if name in files:
            raise SystemExit(f"duplicate env file {name}")
        lines = base_lines(doc, row)
        keys = {ln.split("=", 1)[0] for ln in lines}
        clash = [ln for ln in extra if ln.split("=", 1)[0] in keys]
        if clash:
            raise SystemExit(f"{name}: cell lines {clash} override the base")
        text = HEADER.format(what=what) + "".join(f"{ln}\n" for ln in lines + extra)
        env = dict(ln.split("=", 1) for ln in lines + extra)
        fk.parse_fault_knobs(env)                              # the launch-time parser (raises on a refused cell)
        files[name] = text

    for nom in doc.get("nominals") or []:
        rows = list(BASE_ROWS) + (list(KIND_ROWS) if nom.get("kind_rows") else [])
        for row in rows:
            add(nom["id"], row, nom["payload"], [], f"nominal, {nom['payload']}")
    ids = set()
    for cell in doc["cells"]:
        if cell["id"] in ids:
            raise SystemExit(f"duplicate cell id {cell['id']}")
        ids.add(cell["id"])
        payload = cell.get("payload", "L000")
        rows = list(BASE_ROWS) + (list(KIND_ROWS) if cell.get("kind_rows") else [])
        for row in rows:
            add(cell["id"], row, payload, cell_lines(cell, doc["rows"][row]),
                f"cell {cell['id']} = {cell.get('fault') or 'anchor'}, {payload}")
    for smk in doc.get("smokes") or []:
        for row in smk["rows"]:
            add(smk["id"], row, "L000", cell_lines(smk, doc["rows"][row], onset=smk["onset"]),
                f"smoke {smk['id']} = {smk['fault']} armed, onset {smk['onset']} s")
    n_cells = len(doc["cells"])
    if n_cells != 50:
        raise SystemExit(f"cells.yaml lists {n_cells} cells, the CHARTER 50")
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if envs/ differs from cells.yaml")
    args = ap.parse_args(argv)
    doc = load_cells()
    files = planned(doc)
    on_disk = {p.name for p in ENVS.glob("*.env")} if ENVS.is_dir() else set()
    if args.check:
        missing = sorted(set(files) - on_disk)
        extra = sorted(on_disk - set(files))
        stale = sorted(n for n in set(files) & on_disk if (ENVS / n).read_text() != files[n])
        for label, names in (("missing", missing), ("extra", extra), ("stale", stale)):
            if names:
                print(f"{label}: {names}")
        ok = not (missing or extra or stale)
        print(f"envs/ {'matches' if ok else 'DIFFERS FROM'} cells.yaml ({len(files)} files)")
        return 0 if ok else 1
    extra = sorted(on_disk - set(files))
    if extra:
        raise SystemExit(f"envs/ holds files cells.yaml does not imply: {extra} (remove them by hand first)")
    ENVS.mkdir(parents=True, exist_ok=True)
    changed = 0
    for name, text in sorted(files.items()):
        p = ENVS / name
        if not p.is_file() or p.read_text() != text:
            p.write_text(text)
            changed += 1
    print(f"wrote {changed} / {len(files)} env files under {ENVS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
