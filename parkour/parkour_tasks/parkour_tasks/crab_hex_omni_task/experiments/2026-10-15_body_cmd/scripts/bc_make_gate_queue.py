#!/usr/bin/env python3
"""Write the gate-eval queue for one finished body head (PLAN step 7 / 8): every row the gates read, launched like
the anchors (bc_eval_row.sh; field rows with the row's env block in the PROCESS env, as the anchors' were).

Rows (body head, route term): suite__omni_body es1 + es2, turnlevels__omni_body es1 + es2, field_hard__omni_body
es1-es4, field_light__omni_body es1 + es2, ring_obst__omni_body es1 + es2; reported only (world rows through
world_rate): suite__omni es1, field_hard__omni es1. The driver's own suite_body es1 stamp is NOT reused: every gate
row comes from this queue, so all of a head's reads share one launcher.

    bc_make_gate_queue.py --chain BC_p2a_s18 --name GATE_s18  -> scripts/gate_<name>.sh
"""

from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
C = HERE.parent
R = Path("/home/nickmagus/krabby/krabby-research")
OMNI = R / "parkour/parkour_tasks/parkour_tasks/crab_hex_omni_task"
MB = OMNI / "experiments/eval/scenarios_omni_body.yaml"
MO = OMNI / "experiments/eval/scenarios_omni.yaml"
MP = OMNI / "experiments/2026-10-07_omni_phase2/scenarios_p2.yaml"

spec = importlib.util.spec_from_file_location("_bc_head_env_q", HERE / "bc_head_env.py")
HE = importlib.util.module_from_spec(spec)
spec.loader.exec_module(HE)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--chain", required=True)
    ap.add_argument("--name", required=True)
    a = ap.parse_args()
    ck = json.loads((C / "stage_reads" / f"{a.chain}.json").read_text())["ckpt"]
    envs = C / "envs"
    base = envs / f"{a.name}.env"
    base.write_text("".join(f"{k}={v}\n" for k, v in sorted(HE.head_env(a.chain).items())))
    rows = [(base, MB, "suite__omni_body", es, "") for es in (1, 2)]
    rows += [(base, MB, "turnlevels__omni_body", es, "") for es in (1, 2)]
    for rid, ess in (("field_hard__omni_body", (1, 2, 3, 4)), ("field_light__omni_body", (1, 2)),
                     ("ring_obst__omni_body", (1, 2))):
        fe = envs / f"{a.name}.{rid}.env"
        fe.write_text("".join(f"{k}={v}\n" for k, v in sorted(HE.head_env(a.chain, f"{MB}:{rid}").items())))
        rows += [(fe, MB, rid, es, "") for es in ess]
    wr = "--command-adapter world_rate --adapter-turns on"
    rows += [(base, MO, "suite__omni", 1, wr)]
    fe = envs / f"{a.name}.field_hard__omni.env"
    fe.write_text("".join(f"{k}={v}\n" for k, v in sorted(HE.head_env(a.chain, f"{MP}:field_hard__omni").items())))
    rows += [(fe, MP, "field_hard__omni", 1, wr)]
    L = ["#!/bin/bash", f"# Gate rows for {a.chain} -> {a.name} (generated by bc_make_gate_queue.py)", f"S={HERE}",
         f'echo "GATEQ START {a.name} $(date -Is)"']
    for env, man, sc, es, extra in rows:
        L.append(f"$S/bc_eval_row.sh {a.name} {ck} {env} {man} {sc} {es} {extra}".rstrip())
    L.append(f'echo "GATEQ END {a.name} $(date -Is)"')
    q = HERE / f"gate_{a.name}.sh"
    q.write_text("\n".join(map(str, L)) + "\n")
    q.chmod(0o755)
    print(f"{q}: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
