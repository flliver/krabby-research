#!/usr/bin/env python3
"""Write the step-4b queue (after the envelope freeze): G0 at the final eval_sha, P2, the anchors, the stage anchors.

Every row's env is a RECORDED env: the S1 heads' from their REFS_S1_s<seed> stamps (the matching row's stamp: suite
for suite / turnlevels / grid, field_hard / field_light / ring_obst for the body field rows), the phase-1 stage
heads' from their own recorded suite__omni stamps (ppo_construction; a c5 head takes its seed's c6 stamp env -- the
same eval carry). P2 = S1 s18 zero-shot in BODY mode (its suite env + frame body + the frozen envelope + encoding
none, facing obs clip dropped; no adapter).

    bc_make_step4b.py --envelope envelope_freeze.json   -> scripts/step4b_queue.sh + envs/*.env
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
C = HERE.parent
R = Path("/home/nickmagus/krabby/krabby-research")
OMNI = R / "parkour/parkour_tasks/parkour_tasks/crab_hex_omni_task"
MB = OMNI / "experiments/eval/scenarios_omni_body.yaml"
MO = OMNI / "experiments/eval/scenarios_omni.yaml"
MP = OMNI / "experiments/2026-10-07_omni_phase2/scenarios_p2.yaml"
LR = R / "parkour/outputs/omni_plan/phase2/lr"
PPO = R / "parkour/logs/rsl_rl/gait_eval/omni_phases/2026-10-01_ppo_construction"
RUNS1 = R / "parkour/logs/rsl_rl/crab_hex_omni_flat_walk"
S1 = {16: R / "parkour/logs/rsl_rl/crab_hex_omni_teacher/2026-10-07_15-34-26_seed16_X10_p2a_A15pB/model_19994.pt",
      17: R / "parkour/logs/rsl_rl/crab_hex_omni_teacher/2026-10-07_19-05-32_seed17_X11_p2a_A15pB/model_19994.pt",
      18: R / "parkour/logs/rsl_rl/crab_hex_omni_teacher/2026-10-07_07-50-10_seed18_X08_p2a_A15pB/model_19994.pt"}
#: the B chain's stage heads (ppo_construction heads.json; B = the bound-loss arm): stage -> seed -> (run tag, model)
STAGES = {
    "fb6k": {16: ("seed16_X40_s1_A15pB", "model_5999.pt"), 17: ("seed17_X42_s1_A15pB", "model_5999.pt"),
             18: ("seed18_X43_s1_A15pB", "model_5999.pt")},
    "c4": {16: ("seed16_X55_c4_A15pB", "model_7498.pt"), 17: ("seed17_X56_c4_A15pB", "model_7498.pt"),
           18: ("seed18_X57_c4_A15pB", "model_7498.pt")},
    "c5": {16: ("seed16_X58_c5_A15pB", "model_8997.pt"), 17: ("seed17_X59_c5_A15pB", "model_8997.pt"),
           18: ("seed18_X60_c5_A15pB", "model_8997.pt")},
    "c6": {16: ("seed16_X58_c6_A15pB", "model_10996.pt"), 17: ("seed17_X59_c6_A15pB", "model_10996.pt"),
           18: ("seed18_X60_c6_A15pB", "model_10996.pt")},
    "c6x": {16: ("seed16_X58_c6x_A15pB", "model_14995.pt"), 17: ("seed17_X59_c6x_A15pB", "model_14995.pt"),
            18: ("seed18_X60_c6x_A15pB", "model_14995.pt")},
}


def one(glob_dir: Path) -> Path:
    hits = sorted(p for p in glob_dir.glob("*/") if (p / "run_meta.json").is_file())
    if not hits:
        raise SystemExit(f"no stamp under {glob_dir}")
    return hits[-1]


def env_of(stamp: Path) -> dict:
    return dict(json.loads((stamp / "run_meta.json").read_text())["env_vars"])


def write_env(name: str, env: dict) -> Path:
    p = C / "envs" / f"{name}.env"
    p.parent.mkdir(exist_ok=True)
    p.write_text("".join(f"{k}={v}\n" for k, v in sorted(env.items())))
    return p


def run_dir(tag: str) -> Path:
    hits = sorted(RUNS1.glob(f"*_{tag}"))
    if len(hits) != 1:
        raise SystemExit(f"run dir for {tag}: {hits}")
    return hits[0]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--envelope", default=str(C / "envelope_freeze.json"))
    a = ap.parse_args()
    knobs = json.loads(Path(a.envelope).read_text())["knobs"]
    L = ["#!/bin/bash", "# Step 4b (generated by bc_make_step4b.py): G0 at the final eval_sha, P2, anchors, stage anchors.",
         f"S={HERE}", 'echo "STEP4B START $(date -Is)"']
    row = lambda name, ck, env, man, sc, es, extra="": L.append(
        f"$S/bc_eval_row.sh {name} {ck} {env} {man} {sc} {es} {extra}".rstrip())
    # G0 at the final hash
    row("G0f_S1_s18", S1[18], one(LR / "REFS_S1_s18/suite__omni/seed001"), MO, "suite__omni", 1)
    row("G0f_S1_s18", S1[18], one(LR / "REFS_S1_s18/field_hard__omni/seed001"), MP, "field_hard__omni", 1)
    # P2: S1 s18 zero-shot in body mode (known-bad for STRAIGHT and TURN WORKS)
    p2 = env_of(one(LR / "REFS_S1_s18/suite__omni/seed001"))
    p2.pop("KRABBY_OMNI_FACING_OBS_CLIP", None)
    p2.update({"KRABBY_OMNI_COMMAND_FRAME": "body", "KRABBY_OMNI_FACING_OBS_ENCODING": "none", **knobs})
    p2env = write_env("P2_S1_s18_body", p2)
    for sc in ("suite__omni_body", "turnlevels__omni_body"):
        row("P2_S1_s18", S1[18], p2env, MB, sc, 1)
    # anchors: S1 s18, s16, s17 + body_hold
    for seed in (18, 16, 17):
        name = f"ANC_S1_s{seed}"
        suite_env = one(LR / f"REFS_S1_s{seed}/suite__omni/seed001")
        for es in (1, 2):
            for sc in ("suite__omni_body", "turnlevels__omni_body", "grid__omni_body"):
                row(name, S1[seed], suite_env, MB, sc, es, "--command-adapter body_hold")
        for base, sc, seeds in (("field_hard__omni", "field_hard__omni_body", (1, 2, 3, 4)),
                                ("field_light__omni", "field_light__omni_body", (1, 2)),
                                ("ring_obst__omni", "ring_obst__omni_body", (1, 2))):
            fenv = one(LR / f"REFS_S1_s{seed}/{base}/seed001")
            for es in seeds:
                row(name, S1[seed], fenv, MB, sc, es, "--command-adapter body_hold")
    # stage anchors (step 6 stage-end reads): translation + wz = 0 holds live in suite__omni_body
    for stage, seeds in STAGES.items():
        for seed, (tag, model) in seeds.items():
            src_tag = tag.replace("_c5_", "_c6_")
            senv = one(PPO / src_tag / "suite__omni/seed001")
            row(f"STG_{stage}_s{seed}", run_dir(tag) / model, senv, MB, "suite__omni_body", 1,
                "--command-adapter body_hold")
    L.append('echo "STEP4B END $(date -Is)"')
    q = HERE / "step4b_queue.sh"
    q.write_text("\n".join(str(x) for x in L) + "\n")
    q.chmod(0o755)
    print(f"{q}: {sum(1 for x in L if 'bc_eval_row.sh' in x)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
