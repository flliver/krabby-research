def load_spec(path: Path | None = None) -> dict:
    """The spec at ``path``; a path given explicitly (``--spec``) that does not exist is REFUSED (no silent fallback).
    With no path, ``SPEC_PATH`` is read, and the in-code :data:`DEFAULT_SPEC` stands in only while it is not yet written."""
    if path is not None:
        p = Path(path)
        if not p.is_file():
            raise FileNotFoundError(f"spec {p} does not exist (an explicit --spec is never replaced by the default)")
        return yaml.safe_load(p.read_text())
    return yaml.safe_load(SPEC_PATH.read_text()) if SPEC_PATH.is_file() else copy.deepcopy(DEFAULT_SPEC)


def spec_sha(spec: dict) -> str:
    return hashlib.sha256(json.dumps(spec, sort_keys=True).encode()).hexdigest()


def _scenarios(path: Path) -> dict:
    return {s["id"]: s for s in (yaml.safe_load(Path(path).read_text()).get("scenarios") or [])}


def check_spec(spec: dict) -> None:
    if int(spec.get("schema", 0)) != 1:
        raise ValueError(f"spec schema {spec.get('schema')} (want 1)")
    if list(spec["kinds"]) != list(KINDS):
        raise ValueError(f"spec kinds {spec['kinds']} != the interface's {list(KINDS)} (in that order)")
    want = {b: band_text(*v) for b, v in BANDS.items()}
    if dict(spec["bands"]) != want:
        raise ValueError(f"spec bands {spec['bands']} != the interface's {want}")
    if spec.get("ladder") != "rt":
        raise ValueError(f"spec ladder {spec.get('ladder')!r} (the kind rows run KRABBY_SITE_LADDER=rt)")
    if dict(spec.get("friction") or {}) != {"gravel": GRAVEL_FRICTION}:
        raise ValueError(f"spec friction {spec.get('friction')} != {{'gravel': {GRAVEL_FRICTION!r}}}")
    if int(spec["site_count"]) != 20 or int(spec["episodes"]) != 100 or float(spec["episode_length_s"]) != 80.0:
        raise ValueError("spec site_count / episodes / episode_length_s must be 20 / 100 / 80 (PLAN Eval)")
    if str(spec["legacy_diff"]) != "0.20:1.0":
        raise ValueError("spec legacy_diff must be 0.20:1.0 (KRABBY_FLAT_TERRAIN_DIFF on every kind row)")


def kind_env_block(spec: dict, kind: str, band: str) -> dict:
    env = {"KRABBY_FLAT_TERRAIN_MODE": "light", FLAT_FRAC_VAR: "0.0", "KRABBY_FLAT_TERRAIN_GEOM": "site",
           "KRABBY_SITE_LADDER": str(spec["ladder"]), "KRABBY_SITE_MIX": f"{kind}={int(spec['site_count'])}",
           "KRABBY_SITE_DIFF": str(spec["bands"][band]), "KRABBY_FLAT_TERRAIN_DIFF": str(spec["legacy_diff"])}
    if kind in (spec.get("friction") or {}):
        env[FRICTION_VAR] = str(spec["friction"][kind])
    return env


def kind_row(spec: dict, base: dict, kind: str, band: str) -> dict:
    name, unit, _ = LADDERS[kind]
    lo, hi = band_range(kind, band)
    above = above_envelope(kind, band)
    note = (f"Rough-terrain {kind} {band} (site d {spec['bands'][band]}; {name} {lo:.3g}-{hi:.3g} {unit}; crossing "
            f"radius {CROSS_R[kind]:g} m; {'ABOVE the blind envelope: report only' if above else 'in envelope'})"
            f" on {spec['base_scenario']}'s schedule.")
    return {"id": row_id(kind, band), "role": "teacher", "task": base["task"], "terrain_label": f"rt_{kind}",
            "checkpoint": base.get("checkpoint", "SUPPLIED-PER-RUN--pass---checkpoint"),
            "episodes": int(spec["episodes"]), "env_seed": 1, "episode_length_s": float(spec["episode_length_s"]),
            "spawn_yaw": base.get("spawn_yaw", "first_face"), "schedule": copy.deepcopy(base["schedule"]),
            "env": kind_env_block(spec, kind, band), "notes": note}


def build_manifest(spec: dict) -> dict:
    check_spec(spec)
    base_path = OMNI / spec["base_manifest"]
    base_doc = yaml.safe_load(base_path.read_text())
    base = _scenarios(base_path)[spec["base_scenario"]]
    out = [kind_row(spec, base, k, b) for k in KINDS for b in BANDS]
    doc = {k: v for k, v in base_doc.items() if k != "scenarios"}
    doc["scenarios"] = out
    return doc


def render_manifest(spec: dict, spec_name: str) -> str:
    return (HEADER.format(script="make_manifest.py", spec=spec_name, sha=spec_sha(spec)[:16], base=spec["base_manifest"],
                          base_sc=spec["base_scenario"], fvar=FRICTION_VAR, fval=GRAVEL_FRICTION)
            + yaml.safe_dump(build_manifest(spec), sort_keys=False, width=120))


# ============================================================================== env files
def read_env_file(p: Path) -> dict:
    """``KEY=VALUE`` lines (comments / blanks skipped), as tp_lib.read_env_file (no ``$REPO`` tokens here)."""
    out = {}
    for ln in Path(p).read_text().splitlines():
        if not ln.strip() or ln.lstrip().startswith("#"):
            continue
        k, sep, v = ln.partition("=")
        if not sep:
            raise ValueError(f"{p}: malformed line {ln!r}")
        if k in out:
            raise ValueError(f"{p}: {k} given twice")
        out[k] = v
    return out


def kind_env(spec: dict) -> dict:
    """TDR's field_hard env minus field_hard__omni's own manifest block keys (sorted)."""
    src = read_env_file(OMNI / spec["kind_env_source"])
    base = _scenarios(OMNI / spec["base_manifest"])[spec["base_scenario"]]
    drop = sorted(base.get("env") or {})
    env = {k: v for k, v in src.items() if k.startswith("KRABBY_") and k not in drop}
    bad = sorted(k for k in env if k.startswith(DR_PREFIX) or k == FRICTION_VAR or k.startswith("KRABBY_SITE_"))
    if bad:
        raise ValueError(f"kind env source {spec['kind_env_source']} carries {bad}")
    return dict(sorted(env.items()))


def render_kind_env(spec: dict) -> str:
    base = _scenarios(OMNI / spec["base_manifest"])[spec["base_scenario"]]
    drop = ",".join(sorted(base.get("env") or {}))
    head = ENV_HEADER.format(script="make_manifest.py", src=Path(spec["kind_env_source"]).name,
                             base_sc=spec["base_scenario"], drop=f"({drop})")
    return head + "".join(f"{k}={v}\n" for k, v in kind_env(spec).items())


