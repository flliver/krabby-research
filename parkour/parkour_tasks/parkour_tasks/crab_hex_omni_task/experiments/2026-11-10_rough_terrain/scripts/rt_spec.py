def load_rows(path: Path | None = None) -> dict:
    return json.loads(Path(path or ROWS_PATH).read_text())


def manifest_block(row: dict) -> dict:
    """The row's manifest env block (read from the manifest the row names)."""
    sc = _scenarios(OMNI / row["manifest"]).get(row["scenario"])
    if sc is None:
        raise KeyError(f"{row['scenario']} not in {row['manifest']}")
    return {str(k): str(v) for k, v in (sc.get("env") or {}).items()}


def expected_env(row: dict) -> dict:
    """The process KRABBY_* env a stamp of this row must record (``run_meta.env_vars``): gate_row.sh's composed env
    (the env file's ^KRABBY_ lines, plus a level file's KRABBY_PAYLOAD_* lines) with the manifest block merged over
    it by the harness (eval_crab_hex_gait.py writes the block into os.environ before recording)."""
    env = {k: v for k, v in read_env_file(OMNI / row["env_file"]).items() if k.startswith("KRABBY_")}
    if row.get("level_file"):
        env.update({k: v for k, v in read_env_file(OMNI / row["level_file"]).items()
                    if k.startswith("KRABBY_PAYLOAD_")})
    env.update(manifest_block(row))
    return dict(sorted(env.items()))
