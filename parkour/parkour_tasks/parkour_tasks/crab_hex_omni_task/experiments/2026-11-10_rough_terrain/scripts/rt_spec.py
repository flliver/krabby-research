# ============================================================================== ladders and bands
def band_text(lo: float, hi: float) -> str:
    """``KRABBY_SITE_DIFF`` text of a band (SITE's ``make_site_manifest._band`` form, e.g. ``0:0.3``)."""
    if not (0.0 <= lo <= hi <= 1.0):
        raise ValueError(f"band {lo}:{hi}: need 0 <= lo <= hi <= 1")
    return f"{lo:g}:{hi:g}"


def ladder_value(kind: str, d: float) -> float:
    lo, hi = LADDERS[kind][2]
    return float(lo + (hi - lo) * float(d))


def band_range(kind: str, band: str) -> tuple[float, float]:
    """(bottom, top) of the kind's headline quantity over a band."""
    lo, hi = BANDS[band]
    return ladder_value(kind, lo), ladder_value(kind, hi)


def above_envelope(kind: str, band: str) -> bool:
    """PLAN Design "Blind envelope": a step / drop / pothole band whose bottom exceeds 0.14 m."""
    return kind in ENVELOPE_KINDS and band_range(kind, band)[0] > ENVELOPE_M + 1e-12


def above_envelope_set() -> tuple:
    got = tuple((k, b) for k in KINDS for b in BANDS if above_envelope(k, b))
    if got != ABOVE_ENVELOPE_EXPECTED:
        raise RuntimeError(f"envelope rule gives {got}, PLAN says {ABOVE_ENVELOPE_EXPECTED}")
    return got


def row_id(kind: str, band: str) -> str:
    return f"rt_{kind}_{band}__omni"


