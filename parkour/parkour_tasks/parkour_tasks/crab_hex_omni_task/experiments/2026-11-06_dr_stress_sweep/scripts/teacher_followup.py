#!/usr/bin/env python3
"""Optional T* follow-up of the DR stress sweep (CHARTER §3.6): a FRAGILE term's deciding cells on the teacher.

Runs after ``run_sweep.py`` has ended: it takes the same ``results/run_sweep.lock``, so the two never share the GPU.
For each named cell it runs the two gate rows at es1 and es2 with ``--policy-role teacher`` and the T* checkpoint
(``cells.TSTAR``), on the same Student-Play task and env files (gate names ``DRST_<cell>``). ``--nominal`` adds the
teacher's own nominal at each reference base the named cells use (L000, and L090 for a cell on L090 or a payload
term). Rows go through ``run_sweep.run_row``, so a T* row gets the same launch checks as a student row: tree / pin
check before the row, skip-valid / re-run-invalid, one retry, ``DRS`` sentinels in ``results/run_sweep.log``. Teacher
stamps never count as sweep cells: ``run_sweep.newest_sweep_time`` reads ``DRS_`` stamps only, so the closing nominal
stays current.

The read goes to ``results/teacher.json`` and ``results/teacher.md``. Per seed it gives the same 18 lines, teacher
beside student, and deltas against the teacher nominal when one was run.

    /home/nickmagus/krabby/isaac_venv/bin/python -I teacher_followup.py CELL_ID [CELL_ID ...] [--nominal] [--dry]
    ... teacher_followup.py --read-only CELL_ID ...     re-read existing stamps, run nothing
"""
from __future__ import annotations

import argparse
import fcntl
import json
import signal
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cells as C  # noqa: E402
import run_sweep as RS  # noqa: E402
import stress_read as SR  # noqa: E402

TEACHER = "teacher"


def _nominal_bases(cells: list[dict]) -> list[str]:
    """The teacher nominals the named cells' deltas need (their reference bases only)."""
    return [b for b in ("L000", "L090") if any(SR._ref_base(c) == b for c in cells)]


def run(cells: list[dict], nominal: bool, dry: bool) -> None:
    if not dry:
        pin = RS.check_tree()
        RS.say(f"DRS TEACHER START cells={','.join(c['id'] for c in cells)} nominal={nominal} "
               f"code_sha={pin['code_sha']} eval_sha={pin['eval_sha']}")
    todo = []
    if nominal:
        todo += [(C.nominal_id(b, "A"), None, None, b) for b in _nominal_bases(cells)]
    todo += [(c["id"], C.TERM[c["term"]], c["level"], c["base"]) for c in cells]
    for cid, term, level, base in todo:
        for es in (1, 2):
            for row in C.rows_for(cid, term, level, base, es, policy=TEACHER):
                rc = RS.run_row(row, dry, term, level, base)
                if rc != 0 and not dry:
                    RS.run_row(row, dry, term, level, base, attempt=2)


def read(cells: list[dict]) -> dict:
    out = {"cells": {}, "nominal": {}}
    for b in ("L000", "L090"):
        for es in (1, 2):
            r = SR.cellseed(C.gate_name(C.nominal_id(b, "A"), TEACHER), es, None, None, b, policy=TEACHER)
            if r is not None:
                out["nominal"][f"{b}@{es}"] = r
    for c in cells:
        term = C.TERM[c["term"]]
        ref_base = SR._ref_base(c)
        entry = {"term": c["term"], "level": c["level"], "base": c["base"], "seeds": {}}
        for es in (1, 2):
            t = SR.cellseed(C.gate_name(c["id"], TEACHER), es, term, c["level"], c["base"], policy=TEACHER)
            s = SR.cellseed(C.gate_name(c["id"]), es, term, c["level"], c["base"])
            ref = out["nominal"].get(f"{ref_base}@{es}")
            entry["seeds"][es] = {
                "teacher": t, "student": s,
                "teacher_deltas": (None if t is None or t["pass"] is None or ref is None or ref["pass"] is None
                                   else SR.deltas(t, [ref], flag=c["term"] != "T13")),
            }
        out["cells"][c["id"]] = entry
    return out


def _fmt(v) -> str:
    return "—" if v is None else (f"{v:.3f}" if isinstance(v, float) else str(v))


def _status(r: dict | None) -> str:
    if r is None:
        return "unread"
    if r["pass"] is None:
        return "launch error"
    return "PASS" if r["pass"] else "FAIL " + ", ".join(r["failed"])


def write_md(res: dict, path: Path) -> None:
    lines = ["# T* follow-up (CHARTER §3.6)", "",
             "Teacher = T* (`policy/f19_8_p3b_payload180/model_25992.pt`, `--policy-role teacher`); same task, env "
             "files and lines as the student cells. Generated by `scripts/teacher_followup.py`.", ""]
    if res["nominal"]:
        lines += ["## Teacher nominal", "", "| Base@seed | Status | field_light completion |", "|---|---|---|"]
        for k, r in sorted(res["nominal"].items()):
            comp = (r["lines"].get("field_light_completion") or {}).get("value") if r else None
            lines.append(f"| {k} | {_status(r)} | {_fmt(comp)} |")
        lines.append("")
    lines += ["## Cells", "", "| Cell | Seed | Student | Teacher | Teacher completion |", "|---|---|---|---|---|"]
    for cid, e in res["cells"].items():
        for es, s in sorted(e["seeds"].items()):
            t = s["teacher"]
            comp = (t["lines"].get("field_light_completion") or {}).get("value") if t else None
            lines.append(f"| {cid} | es{es} | {_status(s['student'])} | {_status(t)} | {_fmt(comp)} |")
    lines.append("")
    path.write_text("\n".join(lines))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cells", nargs="+", help="cell ids from cells.cells() (e.g. T07_act_delay_2_L000)")
    ap.add_argument("--nominal", action="store_true", help="also run the teacher nominal (0 kg, plus L090 if needed)")
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--read-only", action="store_true")
    a = ap.parse_args()
    import numpy  # noqa: F401,PLC0415 -- fail fast: the reader needs it (run with the Isaac venv python)

    by_id = {c["id"]: c for c in C.cells()}
    unknown = [x for x in a.cells if x not in by_id]
    if unknown:
        print(f"DRS unknown cell ids {unknown}", flush=True)
        return 2
    cells = [by_id[x] for x in a.cells]
    RS.RESULTS.mkdir(parents=True, exist_ok=True)
    lock = open(RS.RESULTS / "run_sweep.lock", "w")  # noqa: SIM115 -- held for the process lifetime
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        print("DRS another driver holds results/run_sweep.lock", flush=True)
        return 6
    for sig in (signal.SIGTERM, signal.SIGINT, signal.SIGHUP):
        signal.signal(sig, RS._on_signal)
    try:
        if not a.read_only:
            run(cells, a.nominal, a.dry)
        if not a.dry:
            res = read(cells)
            (RS.RESULTS / "teacher.json").write_text(json.dumps(res, indent=1, default=str))
            write_md(res, RS.RESULTS / "teacher.md")
            RS.say(f"DRS TEACHER READ cells={len(res['cells'])} nominal={sorted(res['nominal'])}")
        RS.say("DRS TEACHER END")
        return 0
    except RS.Stop as s:
        RS.say(f"DRS STOP teacher {s.why}")
        return s.code


if __name__ == "__main__":
    sys.exit(main())
