#!/usr/bin/env python3
"""Generate experiments/eval/scenarios_morph.yaml: per-configuration clones of flat_walk_slow_v2,
flat_walk_forward_v2 and a light-obstacle step-onset scenario, selecting the plant via the
manifest ``env:`` block (KRABBY_HEX_USD_PATH) -- informational: the drivers export it into the
process environment. Since 2026-09-09 the config default is the A15+B plant of record
(``assets/crab.usda``): ``__A15pB`` rows carry no override and ``__base`` rows carry the explicit
legacy golden ``assets/variants/crab_simple__splay00_axis5p5in.usda``."""
from pathlib import Path

REPO = Path(__file__).resolve().parents[6]
OUT = REPO / "parkour/parkour_tasks/parkour_tasks/crab_hex_forward_task/experiments/eval/scenarios_morph.yaml"
VARIANTS = REPO / "assets/variants"
# (config name, USDA path or None for the config default = A15+B main asset)
CONFIGS = [("base", VARIANTS / "crab_simple__splay00_axis5p5in.usda"), ("B", VARIANTS / "crab_simple__splay00_axis2p5in.usda"),
           ("A10", VARIANTS / "crab_simple__splay10_axis5p5in.usda"), ("A15", VARIANTS / "crab_simple__splay15_axis5p5in.usda"),
           ("A20", VARIANTS / "crab_simple__splay20_axis5p5in.usda"), ("A10+B", VARIANTS / "crab_simple__splay10_axis2p5in.usda"),
           ("A15+B", None), ("A20+B", VARIANTS / "crab_simple__splay20_axis2p5in.usda")]
LIGHT = {"KRABBY_FLAT_TERRAIN_MODE": "light", "KRABBY_FLAT_TERRAIN_FLAT_FRAC": "0.0",
         "KRABBY_FLAT_TERRAIN_GEOM": "shallow", "KRABBY_FLAT_TERRAIN_DIFF": "0.05:0.2"}
SCHEDULES = {
    "slow": ("36.0", [("0.0", "stand"), ("0.25", "creep"), ("0.35", "low")], {}),
    "fwd": ("36.0", [("0.30", "low"), ("0.475", "mid"), ("0.65", "high")], {}),
    "step": ("36.0", [("0.0", "stand"), ("0.25", "creep"), ("0.35", "low")], LIGHT),
    # diagnostic: training-horizon check (no stand prologue; 18 s of creep like a 20 s training episode)
    "creep20": ("22.0", [("0.25", "creep_a"), ("0.25", "creep_b")], {}),
}
lines = ["# GENERATED by parkour/parkour_tasks/parkour_tasks/crab_hex_forward_task/experiments/2026-09-02_1446_leg_mount_morphology/make_morph_manifest.py",
         "# PLAN G leg-mount morphology campaign: per-configuration eval scenarios. Do not hand-edit.",
         "# NOTE: KRABBY_HEX_USD_PATH below is informational -- the scene config reads it at import",
         "# time, so the campaign drivers ALSO export it in the eval process environment. Since",
         "# 2026-09-09 the config default is the A15+B main asset (assets/crab.usda): __A15pB rows",
         "# carry no override; __base rows name the legacy golden variants/crab_simple__splay00_axis5p5in.usda explicitly.",
         "manifest_version: 2", "", "defaults:", "  prologue_s: 1.5", "  settle_s: 1.0",
         "  min_window_s: 1.0", "  fall_exclusion_s: 0.5", "  contact_force_threshold: 1.0",
         "  slip_speed_threshold: 0.02", "  min_cycles: 2", "  lin_vel_clip: 0.2", "", "scenarios:"]
for cfg, usd in CONFIGS:
    cid = cfg.replace("+", "p")
    for sname, (ep_len, holds, extra_env) in SCHEDULES.items():
        env = dict(extra_env)
        if usd:
            env["KRABBY_HEX_USD_PATH"] = str(usd)
        lines += [f"  - id: {sname}__{cid}", "    role: teacher", "    task: Isaac-Crab-Hex-Flat-Walk-v0",
                  f"    terrain_label: {'light_obstacles' if extra_env else 'flat'}",
                  "    checkpoint: SUPPLIED-PER-RUN--pass---checkpoint", "    episodes: 100",
                  "    env_seed: 1", f"    episode_length_s: {ep_len}", "    schedule:"]
        hold_s = "9.0" if sname == "creep20" else "10.0"
        lines += [f"      - {{vx: {vx}, hold_s: {hold_s}, label: {lab}}}" for vx, lab in holds]
        if env:
            lines.append("    env:")
            lines += [f"      {k}: \"{v}\"" for k, v in env.items()]
        lines.append(f"    notes: PLAN G morphology config {cfg}, {sname} schedule.")
        lines.append("")
OUT.write_text("\n".join(lines))
print("wrote", OUT, "scenarios:", sum(1 for l in lines if l.startswith("  - id:")))
