"""SEN0581 per-robot serial map and udev rendering."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from krabby._sen0581_udev import (
    SEN0581_ROLES,
    draft_role_map_from_serials,
    load_sen0581_role_map,
    normalize_sen0581_serial,
    render_sen0581_udev_rules,
    sen0581_device_path,
    sen0581_device_paths,
    sen0581_symlink_name,
)


def test_normalize_accepts_space_and_underscore() -> None:
    assert normalize_sen0581_serial("AAA111 BBB222") == "AAA111 BBB222"
    assert normalize_sen0581_serial("AAA111_BBB222") == "AAA111 BBB222"


def test_normalize_rejects_empty() -> None:
    with pytest.raises(ValueError):
        normalize_sen0581_serial("  ")


def test_load_and_render_round_trip(tmp_path: Path) -> None:
    cfg = {
        "belly_right": "SER001_RIGHT01",
        "belly_left": "SER002 LEFT02",
        "rear": "SER003 REAR03",
    }
    path = tmp_path / "sen0581.json"
    path.write_text(json.dumps(cfg))
    role_map = load_sen0581_role_map(path)
    assert role_map["belly_right"] == "SER001 RIGHT01"
    rules = render_sen0581_udev_rules(role_map)
    assert 'ATTRS{serial}=="SER001 RIGHT01"' in rules
    assert 'SYMLINK+="krabby-tof-belly-right"' in rules
    assert 'ATTRS{serial}=="SER002 LEFT02"' in rules
    assert 'SYMLINK+="krabby-tof-belly-left"' in rules
    assert 'ATTRS{serial}=="SER003 REAR03"' in rules
    assert 'SYMLINK+="krabby-tof-rear"' in rules
    assert 'ENV{ID_USB_INTERFACE_NUM}=="00"' in rules
    assert "Generated by krabby install" in rules


def test_load_rejects_duplicate_serial(tmp_path: Path) -> None:
    path = tmp_path / "sen0581.json"
    path.write_text(
        json.dumps(
            {
                "belly_right": "SER001 RIGHT01",
                "belly_left": "SER001 RIGHT01",
                "rear": "SER003 REAR03",
            }
        )
    )
    with pytest.raises(ValueError, match="duplicate"):
        load_sen0581_role_map(path)


def test_draft_role_map_sorted() -> None:
    got = draft_role_map_from_serials(
        ["SER003 REAR03", "SER001 LEFT01", "SER002_MID002"]
    )
    assert list(got) == ["belly_right", "belly_left", "rear"]
    assert got["belly_right"] == "SER001 LEFT01"
    assert got["belly_left"] == "SER002 MID002"
    assert got["rear"] == "SER003 REAR03"


def test_device_paths_match_symlink_convention() -> None:
    assert sen0581_symlink_name("belly_right") == "krabby-tof-belly-right"
    assert sen0581_device_path("rear") == "/dev/krabby-tof-rear"
    assert sen0581_device_paths() == (
        "/dev/krabby-tof-belly-right",
        "/dev/krabby-tof-belly-left",
        "/dev/krabby-tof-rear",
    )
    assert len(sen0581_device_paths()) == len(SEN0581_ROLES)


def test_jetson_catalog_sen0581_devices_match_udev_paths() -> None:
    """HAL catalog literals must stay aligned with udev / Docker device paths."""
    from hal.server.jetson.sensor_backend_jetson import JETSON_SENSOR_CATALOG_BY_ID

    role_to_catalog_id = {
        "belly_right": "belly_right_tof",
        "belly_left": "belly_left_tof",
        "rear": "rear_tof",
    }
    for role, catalog_id in role_to_catalog_id.items():
        row = JETSON_SENSOR_CATALOG_BY_ID[catalog_id]
        assert row.sen0581_device == sen0581_device_path(role)
